it.each(['cancel','owner change','unmount'])('does not resume a rate-limited authorization after %s',async ending=>{
  const CfxAuthorization=await component(),received=vi.fn()
  vi.useFakeTimers()
  vi.spyOn(document,'visibilityState','get').mockReturnValue('visible')
  vi.spyOn(window,'open').mockReturnValue(null)
  api.POST.mockResolvedValueOnce({...attempt,mode:'redirect',expiresAt:Date.now()+600_000})
  api.GET.mockRejectedValueOnce(new ExAxiosError('http','CFX_REQUEST_LIMITED','limited',{status:429,retryAfterSeconds:30}))
  const view=render(<CfxAuthorization token="owner" onTicket={received}/>)
  await act(async()=>fireEvent.click(screen.getByRole('button',{name:'使用 Cfx'})))
  const signal=api.GET.mock.calls[0]![1].signal as AbortSignal
  expect(api.DELETE).not.toHaveBeenCalled()
  if(ending==='cancel')await act(async()=>fireEvent.click(screen.getByRole('button',{name:'取消 Cfx 授权'})))
  else if(ending==='owner change')view.rerender(<CfxAuthorization token="other-owner" onTicket={received}/>)
  else view.unmount()
  expect(signal.aborted).toBe(true)
  await act(()=>vi.advanceTimersByTimeAsync(60_000))
  await act(async()=>document.dispatchEvent(new Event('visibilitychange')))
  expect(api.GET).toHaveBeenCalledTimes(1)
  expect(received).not.toHaveBeenCalled()
  expect(api.DELETE).toHaveBeenCalledTimes(1)
})
